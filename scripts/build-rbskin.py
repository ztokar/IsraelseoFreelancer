"""Write rbskin.css: the dark Banner look for older pages that keep their own markup and copy (class "rbskin" on the .gp root).
It reads site.css, finds every rule that hard-codes a light surface or white-on-green text, and emits a dark override.
Run after editing site.css:  python scripts/build-rbskin.py"""
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
css = re.sub(r"/\*.*?\*/", "", (ROOT / "site.css").read_text(encoding="utf-8"), flags=re.S)
css = re.sub(r"@media[^{]+\{((?:[^{}]*\{[^{}]*\})*)\s*\}", r"\1", css)  # flatten media blocks
css = re.sub(r"@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*\s*\}", "", css)

LIGHT = re.compile(r"background(?:-color)?\s*:[^;}]*(#fff\b|#ffffff|#fbfbf8|#fff7e6|#EDF5FF|rgba\(228,246,238)", re.I)
GREEN_BG = re.compile(r"background(?:-color)?\s*:[^;}]*var\(--green(?:-bright|-dark)?\)")
WHITE_TXT = re.compile(r"(?<![-a-z])color\s*:\s*#fff\b", re.I)
SHADOW = re.compile(r"box-shadow\s*:[^;}]*rgba\(15,17,21")


def scope(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if not s or s.startswith("@") or "%" in s:
            continue
        out.append(re.sub(r"^\.gp(?![\w-])", ".gp.rbskin", s) if s.startswith(".gp") else ".gp.rbskin " + s)
    return ",".join(out)


INK_BG = re.compile(r"background(?:-color)?\s*:\s*var\(--ink\)")
HEX = re.compile(r"(?<![-a-z])color\s*:\s*(#[0-9a-fA-F]{3,6})\b")


def dark(h):
    h = h.lstrip("#")
    h = "".join(ch * 2 for ch in h) if len(h) == 3 else h
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b < 120


surf, ink, flat, soft = [], [], [], []
for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
    s = scope(sel)
    if not s:
        continue
    if LIGHT.search(body):
        surf.append(s)
    m = HEX.search(body)
    if m and dark(m.group(1)) and not GREEN_BG.search(body):
        soft.append(s)
    if WHITE_TXT.search(body) and (GREEN_BG.search(body) or INK_BG.search(body)):
        ink.append(s)
    if SHADOW.search(body):
        flat.append(s)

HEAD = """/* Generated by scripts/build-rbskin.py. The dark Banner look for older pages (class rbskin on the .gp root). Copy and markup untouched. */
.gp.rbskin{--ink:var(--rb-ink);--ink-soft:#d5e1da;--muted:var(--rb-soft);--offwhite:var(--rb-surface);--green:var(--rb-accent);--green-bright:var(--rb-accent);--green-dark:var(--rb-accent);--green-tint:var(--rb-surface);--hair:var(--rb-line);--gshadow:none;background:var(--rb-canvas);color:var(--ink-soft)}
.gp.rbskin h1,.gp.rbskin h2,.gp.rbskin h3{font-family:var(--rb-display);color:var(--rb-ink);letter-spacing:-.03em}
.gp.rbskin section{background-color:var(--rb-canvas)}
.gp.rbskin a:focus-visible,.gp.rbskin button:focus-visible{outline:2px solid var(--rb-accent);outline-offset:3px}
.gp.rbskin .rbform label,.gp.rbskin form label{color:var(--rb-soft)}
.gp.rbskin form input,.gp.rbskin form textarea{background:var(--rb-surface);border:1px solid var(--rb-line);color:var(--rb-ink)}
.gp.rbskin form button[type=submit]{background:var(--rb-accent);color:var(--rb-accent-ink);box-shadow:none}
.gp.rbskin .btn-primary,.gp.rbskin a.btn-primary{background:var(--rb-accent)!important;color:var(--rb-accent-ink)!important;opacity:1;filter:none}
.gp.rbskin .btn-primary svg{stroke:var(--rb-accent-ink)}
"""
out = HEAD
if surf:
    out += ",\n".join(dict.fromkeys(surf)) + "{background:var(--rb-surface);border-color:var(--rb-line)}\n"
if ink:
    out += ",\n".join(dict.fromkeys(ink)) + "{color:var(--rb-accent-ink)}\n"
if soft:
    out += ",\n".join(dict.fromkeys(soft)) + "{color:var(--rb-soft)}\n"
if flat:
    out += ",\n".join(dict.fromkeys(flat)) + "{box-shadow:none}\n"
out += ".gp.rbskin h1,.gp.rbskin h2,.gp.rbskin h3{color:var(--rb-ink)!important}\n"
(ROOT / "rbskin.css").write_text(out, encoding="utf-8")
print("surfaces", len(surf), "| dark text on green", len(ink), "| shadows", len(flat))
